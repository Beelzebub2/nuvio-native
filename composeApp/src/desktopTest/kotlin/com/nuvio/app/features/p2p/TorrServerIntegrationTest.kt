class TorrServerIntegrationTest {
    @Test fun bundledWindowsEngineAcceptsTheDesktopPreferences() = runBlocking {
        assumeTrue(System.getProperty("os.name").startsWith("Windows"))
        val root = File(System.getProperty("user.dir"))
        val binary = listOf(
            File(root, "src/desktopMain/resources/torrserver/windows-amd64/TorrServer.exe"),
            File(root, "composeApp/src/desktopMain/resources/torrserver/windows-amd64/TorrServer.exe"),
        ).firstOrNull { it.isFile && it.length() > 1_000_000 } ?: error("Bundled engine missing")
        val dir = Files.createTempDirectory("nuvio-owned-engine-test").toFile()
        val backend = TorrServerBackend(dir, File(dir, "cache"), binary)
        val client = HttpClient.newBuilder().version(HttpClient.Version.HTTP_1_1).connectTimeout(Duration.ofSeconds(2)).build()
        try {
            val started = System.nanoTime()
            backend.restart(P2pSettingsUiState(enableUpload = false, cacheSize = P2pCacheSize.NONE,
                torrentProfile = P2pTorrentProfile.BALANCED))
            println("Prepared bundled engine in ${(System.nanoTime() - started) / 1_000_000}ms")
            val url = backend.getStreamUrl("magnet:", 1).substringBefore("/stream")
            val response = client.send(HttpRequest.newBuilder(URI("$url/settings"))
                .timeout(Duration.ofSeconds(8)).header("Content-Type", "application/json")
                .POST(HttpRequest.BodyPublishers.ofString("""{"action":"get"}""")).build(),
                HttpResponse.BodyHandlers.ofString())
            assertEquals(200, response.statusCode())
            val applied = Json.parseToJsonElement(response.body()).jsonObject
            assertEquals(JsonPrimitive(268435456L), applied["CacheSize"])
            assertEquals(JsonPrimitive(false), applied["UseDisk"])
            assertEquals(JsonPrimitive(true), applied["DisableUpload"])
            assertEquals(JsonPrimitive(100), applied["ConnectionsLimit"])
            assertEquals(JsonPrimitive(50), applied["PreloadCache"])
            assertEquals(JsonPrimitive(95), applied["ReaderReadAHead"])
            assertEquals(JsonPrimitive(0), applied["RetrackersMode"])
            assertEquals(applied, desktopTorrentSettings(applied, P2pSettingsUiState(
                enableUpload = false, cacheSize = P2pCacheSize.NONE,
            ), File(dir, "cache").absolutePath), "The running profile must not require a second client rebuild")
        } finally {
            backend.stop()
            client.shutdownNow()
            dir.deleteRecursively()
        }
    }

    @Test fun bundledEngineServesExactBeginningTailAndSeekRangesFromALocalFixture() = runBlocking {
        assumeTrue(System.getProperty("os.name").startsWith("Windows"))
        val root = File(System.getProperty("user.dir"))
        val binary = listOf(
            File(root, "src/desktopMain/resources/torrserver/windows-amd64/TorrServer.exe"),
            File(root, "composeApp/src/desktopMain/resources/torrserver/windows-amd64/TorrServer.exe"),
        ).firstOrNull { it.isFile && it.length() > 1_000_000 } ?: error("Bundled engine missing")
        // Generated bytes owned by this test, served only by a loopback BT peer.
        val payload = ByteArray(4 * 1024 * 1024) { ((it * 31 + it / 997) and 255).toByte() }
        val seed = LocalTorrentSeed(payload)
        val dir = Files.createTempDirectory("nuvio-local-torrent-fixture").toFile()
        val backend = TorrServerBackend(File(dir, "config"), File(dir, "cache"), binary)
        val client = HttpClient.newBuilder().version(HttpClient.Version.HTTP_1_1).connectTimeout(Duration.ofSeconds(2)).build()
        try {
            val settings = P2pSettingsUiState(enableUpload = false, cacheSize = P2pCacheSize.NONE)
            prepareTorrServerSettingsFile(File(dir, "config"), File(dir, "cache"), settings)
            val settingsFile = File(dir, "config/settings.json")
            val seeded = Json.parseToJsonElement(settingsFile.readText()).jsonObject
            val isolated = JsonObject(seeded.getValue("BitTorr").jsonObject + mapOf(
                "DisableDHT" to JsonPrimitive(true), "DisableUPNP" to JsonPrimitive(true),
                "DisablePEX" to JsonPrimitive(true), "EnableLPD" to JsonPrimitive(false),
            ))
            settingsFile.writeText(JsonObject(seeded + ("BitTorr" to isolated)).toString())
            backend.restart(settings)
            val hash = backend.addTorrent(seed.torrentUrl)
            withTimeout(15_000L) {
                while (backend.getTorrentStats(hash).files.none { it.length == payload.size.toLong() }) delay(100)
            }
            val id = backend.getTorrentStats(hash).files.single().id
            val url = backend.getStreamUrl("magnet:?xt=urn:btih:$hash", id)
            for (start in listOf(0, payload.size - 8192, 1024 * 1024, 0)) {
                val end = start + 8191
                val response = try {
                    client.send(HttpRequest.newBuilder(URI(url))
                        .timeout(Duration.ofSeconds(20)).header("Range", "bytes=$start-$end").GET().build(),
                        HttpResponse.BodyHandlers.ofByteArray())
                } catch (error: Exception) {
                    throw AssertionError("Range $start-$end failed; seed blocks=${seed.blocksServed.get()} failure=${seed.failure.get()}", error)
                }
                assertEquals(206, response.statusCode())
                assertEquals("bytes $start-$end/${payload.size}", response.headers().firstValue("Content-Range").orElse(null))
                assertContentEquals(payload.copyOfRange(start, end + 1), response.body())
            }
            assertTrue(seed.blocksServed.get() > 0, "Payload must arrive through the loopback BitTorrent peer")
            assertTrue(backend.isHealthy())
            assertEquals(hash, backend.addTorrent("magnet:?xt=urn:btih:$hash"), "Re-adding must retain the existing torrent")
        } finally {
            backend.stop()
            client.shutdownNow()
            seed.close()
            dir.deleteRecursively()
        }
    }
}
