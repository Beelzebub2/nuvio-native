'use strict';
var assert = require('assert');
var createRecency = require('./recency-list.cjs');
var createCache = require('./bounded-store.cjs');
var list = createRecency();
assert.equal(list.oldest(), null);
assert.equal(list.length(), 0);
for (var i = 0; i < 3500; i++) list.touch(i);
assert.equal(list.length(), 3500);
assert.equal(list.oldest(), 0);
list.touch(0);
assert.equal(list.oldest(), 1);
list.touch(0);
assert.equal(list.length(), 3500, 'Touching an existing piece must not add an entry');
assert(list.remove(1));
assert.equal(list.oldest(), 2);
assert(list.remove('3499'));
assert.equal(list.oldest(), 2);
assert.equal(list.remove(99999), false);
list.clear();
assert.equal(list.oldest(), null);
assert.equal(list.length(), 0);
list.touch(0);
assert.equal(list.oldest(), 0, 'A zero-valued piece index must remain valid');

var evicted = [], cache = createCache(32, function (index) { evicted.push(index); });
var store = cache.factory(16), block = new Buffer(16);
block.fill(7);
store.put(0, block, function (err) { assert.ifError(err); });
store.put(1, block, function (err) { assert.ifError(err); });
store.get(0, function (err, data) { assert.ifError(err); assert.equal(data.length, 16); });
store.put(2, block, function (err) { assert.ifError(err); });
assert.deepEqual(evicted, [1], 'LRU must discard the least recently touched piece');
assert.equal(cache.stats.bytes, 32);
store.get(2, { offset: 4, length: 8 }, function (err, data) {
  assert.ifError(err); assert.equal(data.length, 8); assert(data.equals(block.slice(4, 12)));
});
store.get(1, function (err) { assert(err, 'Evicted piece must be absent'); });
store.close(function (err) { assert.ifError(err); });
assert.equal(cache.stats.bytes, 0);
console.log('O(1) recency/eviction/partial-buffer-slice: PASS on ' + process.version);
